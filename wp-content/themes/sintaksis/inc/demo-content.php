    $genres = ['Роман' => 'roman', 'Стихи' => 'stihi', 'Рассказы' => 'rasskazy', 'Повесть' => 'povest', 'Автофикшн' => 'avtofikshn', 'Проза' => 'proza'];

    foreach ($genres as $name => $slug) {
        $term = get_term_by('name', $name, 'genre');
        $term ? wp_update_term($term->term_id, 'genre', ['slug' => $slug]) : wp_insert_term($name, 'genre', ['slug' => $slug]);
    }

    $log[] = 'Жанры: ' . implode(', ', array_keys($genres));

