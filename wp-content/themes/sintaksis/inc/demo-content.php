        $found = get_posts(['post_type' => $type, 'title' => $stub_title, 'post_status' => 'publish', 'numberposts' => 1]);
        if ($found) wp_trash_post($found[0]->ID);
    }

    flush_rewrite_rules();
    $log[] = 'Постоянные ссылки обновлены';

    return $log;
