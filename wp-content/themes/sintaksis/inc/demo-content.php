        ]);

        if (is_wp_error($id)) continue;

        $book_ids[$slug] = $id;
        $created++;

        foreach ($book['meta'] as $key => $value) {
            update_post_meta($id, '_sx_' . $key, $value);
        }

        wp_set_object_terms($id, [$book['genre']], 'genre');
        wp_set_object_terms($id, [$book['author']], 'book_author');

        if (!empty($book['bio'])) {
            $term = get_term_by('name', $book['author'], 'book_author');
            if ($term) wp_update_term($term->term_id, 'book_author', ['description' => $book['bio']]);
        }
    }

    $log[] = "Книги: добавлено {$created}, всего в каталоге " . count($book_ids);

    // --- Материалы журнала -------------------------------------------------
    $created = 0;

    foreach (sx_demo_articles() as $slug => $article) {
        if (get_page_by_path($slug, OBJECT, 'post')) continue;

        $id = wp_insert_post([
            'post_type'    => 'post',
            'post_status'  => 'publish',
            'post_title'   => $article['title'],
            'post_name'    => $slug,
            'post_excerpt' => $article['excerpt'],
            'post_content' => sx_demo_blocks($article['content']),
            'post_date'    => $article['date'],
        ]);

        if (is_wp_error($id)) continue;
        $created++;

        foreach ($article['meta'] as $key => $value) {
            if ($key === 'inset_book') {
                $value = $book_ids[$value] ?? '';
                if ($value === '') continue;
            }
            update_post_meta($id, '_sx_' . $key, (string) $value);
        }

        $term = get_term_by('name', $article['category'], 'category');
        if ($term) wp_set_post_categories($id, [$term->term_id]);
