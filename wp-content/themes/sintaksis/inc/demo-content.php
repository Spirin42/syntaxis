                'figures'   => "2019 | год, когда вышла первая книга\n47 | книг в каталоге\n8–10 | книг в год\n12 | дебютов",
                'people'    => "Нина Аверьянова | главный редактор\nЮля Мещерская | редактор, журнал\nГриша Полторак | художник, обложки\nТимур Садыков | производство и типографии\nЛена Ковтун | продажи и магазины",
                'contacts'  => "post@sintaksis.press | mailto:post@sintaksis.press\nТелеграм | #",
            ],
            'content' => <<<'TXT'
