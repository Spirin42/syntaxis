    update_option('category_base', 'rubrika');
    $log[] = 'Настройки сайта и постоянные ссылки';

    // --- Рубрики журнала --------------------------------------------------
    wp_update_term(1, 'category', ['name' => 'Эссе', 'slug' => 'esse']);
    foreach (['Интервью' => 'interview', 'Рецензия' => 'recenziya', 'Хроника' => 'hronika'] as $name => $slug) {
        if (!term_exists($slug, 'category')) wp_insert_term($name, 'category', ['slug' => $slug]);
    }
    $log[] = 'Рубрики: Эссе, Интервью, Рецензия, Хроника';

