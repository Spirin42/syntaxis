            continue;
        }

        $id = wp_insert_post([
            'post_type'    => 'book',
            'post_status'  => 'publish',
            'post_title'   => $book['title'],
            'post_name'    => $slug,
            'post_excerpt' => $book['excerpt'] ?? '',
