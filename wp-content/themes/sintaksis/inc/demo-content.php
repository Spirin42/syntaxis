/** Простой формат в блоки редактора: «## » — заголовок, «> » — цитата. */
function sx_demo_blocks(string $text): string {
    $blocks = [];

    foreach (preg_split('/\n\s*\n/', trim($text)) as $chunk) {
        $chunk = trim($chunk);
        if ($chunk === '') continue;

        if (str_starts_with($chunk, '## ')) {
            $h = substr($chunk, 3);
            $blocks[] = "<!-- wp:heading -->\n<h2 class=\"wp-block-heading\">{$h}</h2>\n<!-- /wp:heading -->";
        } elseif (str_starts_with($chunk, '> ')) {
            $q = substr($chunk, 2);
            $blocks[] = "<!-- wp:quote -->\n<blockquote class=\"wp-block-quote\"><p>{$q}</p></blockquote>\n<!-- /wp:quote -->";
        } else {
            $blocks[] = "<!-- wp:paragraph -->\n<p>{$chunk}</p>\n<!-- /wp:paragraph -->";
        }
    }

    return implode("\n\n", $blocks);
}

